def detect_terms(text: str, max_terms: int = 6) -> list[tuple[str, str]]:
    """
    在文本中检测出现的术语关键词，返回 [(术语名, 解释), ...]，最多 max_terms 条。
    同一术语名只出现一次（去重）；中英文 key 均可命中。
    """
    shown: set[str] = set()
    results: list[tuple[str, str]] = []
    for keyword, (term_name, explanation) in _GLOSSARY.items():
        if keyword in text and term_name not in shown:
            shown.add(term_name)
            results.append((term_name, explanation))
        if len(results) >= max_terms:
            break
    return results


def build_glossary_element(text: str, max_terms: int = 5) -> dict | None:
    """
    检测文本中的术语，构建飞书卡片 note 元素。
    若无匹配术语则返回 None。
    """
    terms = detect_terms(text, max_terms=max_terms)
    if not terms:
        return None

    lines = ["📖 本期术语说明"]
    for term_name, explanation in terms:
        lines.append(f"· {term_name}：{explanation}")

    return {
        "tag": "note",
        "elements": [{"tag": "plain_text", "content": "\n".join(lines)}],
    }


# 周报价值卡固定展示的「选股套路」小课堂（P3：与上面术语库同源，不再各写一份）
_STRATEGY_TERMS = ["RSI", "布林", "量价齐升", "动量突破", "金叉", "多头排列"]


def strategy_glossary_md() -> str:
    """渲染固定的「选股套路小课堂」markdown 块（周报价值卡用）。"""
    lines = ['**📖 名词小课堂（这些"套路"是什么意思）**']
    seen: set[str] = set()
    for key in _STRATEGY_TERMS:
        term_name, explanation = _GLOSSARY[key]
        if term_name in seen:
            continue
        seen.add(term_name)
        lines.append(f"• **{term_name}**：{explanation}")
    lines.append('_这些是"什么形态出现时买，历史上更容易跑赢大盘"的经验规律，不是稳赚公式_')
    return "\n".join(lines)
